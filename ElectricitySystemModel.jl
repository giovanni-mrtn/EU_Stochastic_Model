"""
Build_Stochastic_Model(problem, input, scenario_data)

Construct the JuMP stochastic optimization model.
- `problem` contains model options and parameters
- `input` contains prepared inputs and static tables
- `scenario_data` contains scenario-level time series (CF, load, inflows) and probabilities

Returns a named tuple with the model and references to important JuMP variables (Capacity, Electricity, TransmissionCapacity, etc.).
"""
function Build_Stochastic_Model(problem, input, scenario_data)
    @unpack REGION, PLANT, TECH, PERIOD, no_periods, no_regions, no_plants, no_techs, inv_cost, fixed_cost, var_cost, fuel_cost, eta, discharge_time,
        emissionfactor, crf, maxcap, hydroreservoir, PSopenReservoir, PSclosedReservoir, min_reservoir_level, transmissioncost, distance, valid_links, max_transmission, loss_per_K_Km, crf_t = input
    @unpack SCENARIO, load, cf, res_inflow, ror_inflow, PS_inflow, prob = scenario_data 
    @unpack carbon_cap, storage, transmission, transmission_constrained, nuclear, time_step, load_shedding_cost, planned_outage_rate, load_shedding_ratio, fix_hydro = problem
    println("\nBuilding models...")
 
    m = Model(Gurobi.Optimizer)
    set_optimizer_attributes(m, "Threads" => 0, "Method"=> 2, "Crossover"=> 0, "TimeLimit" => 10000)

    
    @variables m begin
        # OperationalCost[s]: operational cost for scenario s (€/year)
        # FixedCost[s]: fixed (annualized) cost (€/year)
        # TotalSheddedLoadCost[s]: cost for load shedding in scenario s (€/year)
        # TotalEmissions[s]: total annual emissions in scenario s (ton CO2/year)
        # InvestmentCost: total annual investment cost (€/year)
        # Electricity[s,r,p,h]: Electricity generated by technology p in region r under scenario s at time step h (MWh)
        # SheddedLoad[s,r,h]: shedded load in region r under scenario s at time step h (MWh)
        # Capacity[r,p]: installed capacity for tech p in region r (MW); for Battery capacity is in MWh
        # ChargeLevel, ReservoirLevel, PSopen/closedLevel, H2StorageLevel: storage state variables (MWh)
        # Transmission and TransmissionCapacity: inter-regional flows (MWh) and line capacities (MW)
        # PlannedOutage[s,r,h]: planned outage power for nuclear plants (MW)

        OperationalCost[s in SCENARIO]                                           >= 0        # €
        FixedCost[s in SCENARIO]                                                 >= 0        # €
        TotalSheddedLoadCost[s in SCENARIO]                                      >= 0        # €
        TotalEmissions[s in SCENARIO]                                            >= 0        # ton CO2
        InvestmentCost                                                           >= 0        # €
        Electricity[s in SCENARIO, r in REGION, p in TECH, h in PERIOD]          >= 0        # MWh/h
        SheddedLoad[s in SCENARIO, r in REGION, h in PERIOD]                     >= 0        # MWh/h
        Capacity[r in REGION, p in TECH]                                         >= 0        # MW, MWh for Battery
        ChargeLevel[s in SCENARIO, r in REGION, h in PERIOD]                     >= 0        # MWh
        ReservoirLevel[s in SCENARIO, r in REGION, h in PERIOD]                  >= 0        # MWh
        PSopenLevel[s in SCENARIO, r in REGION, h in PERIOD]                     >= 0        # MWh  
        PSclosedLevel[s in SCENARIO, r in REGION, h in PERIOD]                   >= 0        # MWh 
        H2StorageLevel[s in SCENARIO, r in REGION, h in PERIOD]                  >= 0        # MWh
        Transmission[s in SCENARIO, r in REGION, r1 in REGION, h in PERIOD; valid_links[r, r1]]       >= 0        # MWh/h
        TransmissionCapacity[r in REGION, r1 in REGION; r1 > r && valid_links[r, r1]]                 >= 0        # MW	
        PlannedOutage[s in SCENARIO, r in REGION, h in PERIOD]                   >= 0        # MW 
    end #variables
    
    for r in REGION, p in TECH
        set_upper_bound(Capacity[r, p], maxcap[r, p])
    end

    if !storage
        for r in REGION
            set_upper_bound(Capacity[r,:Battery], 0.0)
        end
    end

    if !transmission
        for r in REGION
            for r1 in REGION
                if r1 > r && valid_links[r, r1] == true
                    set_upper_bound(TransmissionCapacity[r, r1], 0.0)
                end
            end
        end
    end

    # If the transmission grid is constrained, set upper bounds on transmission capacities
    if transmission_constrained
        for r in REGION
            for r1 in REGION
                if r1 > r && valid_links[r, r1] == true
                    set_upper_bound(TransmissionCapacity[r, r1], max_transmission[r, r1])
                end
            end
        end
    end

    if !nuclear
        for r in REGION
            set_upper_bound(Capacity[r, :Nuclear], 0.0)    
        end   
    end

    if fix_hydro
        for r in REGION, p in [:HydroRes, :HydroRoR, :PSHopenTurb, :PSHopenPump, :PSHclosedTurb, :PSHclosedPump]
            fix(Capacity[r, p], maxcap[r, p], force = true)
        end
    end

    @constraints m begin
        # ELECTRICITY GENERATION
        Generation_0[s in SCENARIO, r in REGION, p in PLANT, h in PERIOD; p != :Nuclear],
            Electricity[s, r, p, h] <= Capacity[r, p] * cf[s, r, p, h] * time_step

        Generation_1[s in SCENARIO, r in REGION, h in PERIOD],
            Electricity[s, r, :Nuclear, h] <= Capacity[r, :Nuclear] * time_step - PlannedOutage[s, r, h]

        # BATTERIES & INVERTER
        InverterCapacity[s in SCENARIO, r in REGION, h in PERIOD], 
            Electricity[s, r, :Inverter, h] + Electricity[s, r, :Battery, h] <= Capacity[r, :Inverter] * time_step

        ChargeDischargeCapacity[r in REGION],
            discharge_time * Capacity[r, :Inverter] <= Capacity[r, :Battery]

        StorageSize[s in SCENARIO, r in REGION, h in PERIOD],
            ChargeLevel[s, r, h] <= Capacity[r, :Battery]

        ElecStorageBalance[s in SCENARIO, r in REGION, h in PERIOD],
            ChargeLevel[s, r, h] <= ChargeLevel[s, r, h>1 ? h-1 : length(PERIOD)] + eta[:Inverter] * Electricity[s, r, :Battery, h] +
            - Electricity[s, r, :Inverter, h]/eta[:Inverter]

        # ELECTRICITY TRANSMISSION
        ElecTransmission[s in SCENARIO, r in REGION, r1 in REGION, h in PERIOD; r1 > r && valid_links[r, r1]], 
        	Transmission[s, r, r1, h] + Transmission[s, r1, r, h] <= TransmissionCapacity[r, r1]* time_step

        # NUCLEAR
        OutagePlanned[s in SCENARIO, r in REGION],
            sum(PlannedOutage[s, r, h] for h in PERIOD) == planned_outage_rate * no_periods * Capacity[r, :Nuclear] * time_step 

        # HYDROPOWER RESERVOIR
        ReservoirBalance[s in SCENARIO, r in REGION, h in PERIOD],
           ReservoirLevel[s, r, h] <= ReservoirLevel[s, r, h>1 ? h-1 : length(PERIOD)] + res_inflow[s, r, h] * time_step +
            - Electricity[s, r, :HydroRes, h] / eta[:HydroRes]

        ReservoirSize[s in SCENARIO, r in REGION, h in PERIOD],
            ReservoirLevel[s, r, h] <= hydroreservoir[r] * 1e6

        MinReservoirLevel[s in SCENARIO, r in REGION, h in PERIOD],
            ReservoirLevel[s, r, h] >= min_reservoir_level[r] * hydroreservoir[r] * 1e6

        # HYDROPOWER ROR
        HydroRoRGeneration[s in SCENARIO, r in REGION, h in PERIOD],
            Electricity[s, r, :HydroRoR, h] <= ror_inflow[s, r, h] * time_step
        
        # PUMPED STORAGE HYDROPOWER
        PSopenBalance[s in SCENARIO, r in REGION, h in PERIOD],
            PSopenLevel[s,r,h] <= PSopenLevel[s, r, h>1 ? h-1 : length(PERIOD)] + 
            + Electricity[s,r,:PSHopenPump,h] * eta[:PSHopenPump] - Electricity[s,r,:PSHopenTurb,h] / eta[:PSHopenTurb] + PS_inflow[s,r,h] * time_step
            
        PSclosedBalance[s in SCENARIO, r in REGION, h in PERIOD],
            PSclosedLevel[s,r,h] <= PSclosedLevel[s, r, h>1 ? h-1 : length(PERIOD)] +
            + Electricity[s,r,:PSHclosedPump,h] * eta[:PSHclosedPump] - Electricity[s,r,:PSHclosedTurb,h] / eta[:PSHclosedTurb]
        
        
        PowerBoundsPSHopenTurb[s in SCENARIO, r in REGION, h in PERIOD],
            Electricity[s,r,:PSHopenTurb,h] <= Capacity[r, :PSHopenTurb] * time_step

        PowerBoundsPSHopenPump[s in SCENARIO, r in REGION, h in PERIOD],
            Electricity[s,r,:PSHopenPump,h] <= Capacity[r, :PSHopenPump] * time_step

        PowerBoundsPSHclosedTurb[s in SCENARIO, r in REGION, h in PERIOD],
            Electricity[s,r,:PSHclosedTurb,h] <= Capacity[r, :PSHclosedTurb] * time_step

        PowerBoundsPSHclosedPump[s in SCENARIO, r in REGION, h in PERIOD],
            Electricity[s,r,:PSHclosedPump,h] <= Capacity[r, :PSHclosedPump] * time_step
        

        PSopenReservoirSize[s in SCENARIO, r in REGION, h in PERIOD],
            PSopenLevel[s, r, h] <= PSopenReservoir[r] * 1e6     # [MWh]

        PSclosedReservoirSize[s in SCENARIO, r in REGION, h in PERIOD],
            PSclosedLevel[s, r, h] <= PSclosedReservoir[r] * 1e6     # [MWh]

            
        MinPSopenReservoirLevel[s in SCENARIO, r in REGION, h in PERIOD],
            PSopenLevel[s, r, h] >= min_reservoir_level[r] * PSopenReservoir[r] * 1e6

        # HYDROGEN
        PowerBoundsH2GT[s in SCENARIO, r in REGION, h in PERIOD],
			Electricity[s,r,:H2GT,h] <= Capacity[r,:H2GT] * time_step

        PowerBoundsElectrolyzer[s in SCENARIO, r in REGION, h in PERIOD],
            Electricity[s,r,:Electrolyzer,h] * eta[:Electrolyzer] <= Capacity[r,:Electrolyzer] * time_step
        
        H2StorageSize[s in SCENARIO, r in REGION, h in PERIOD],
            H2StorageLevel[s, r, h] <= Capacity[r, :H2Storage]

        H2StorageBalance[s in SCENARIO, r in REGION, h in PERIOD],
            H2StorageLevel[s, r, h] <= H2StorageLevel[s, r, h>1 ? h-1 : length(PERIOD)] + 
            + Electricity[s,r,:Electrolyzer,h] * eta[:Electrolyzer] - Electricity[s, r, :H2GT, h] / eta[:H2GT]

        # SYSTEM ENERGY BALANCE
        ElecDemand[s in SCENARIO, r in REGION, h in PERIOD],
            sum(Electricity[s, r, p, h] for p in PLANT) +
            - Electricity[s, r, :Battery, h] - Electricity[s, r, :PSHopenPump, h] - Electricity[s, r, :PSHclosedPump, h] - Electricity[s, r, :Electrolyzer, h] + 
            + Electricity[s, r, :Inverter, h] + Electricity[s, r, :PSHopenTurb, h] + Electricity[s, r, :PSHclosedTurb, h]  + Electricity[s, r, :H2GT, h] + 
            + sum((1- loss_per_K_Km)^(distance[r1, r] / 1000) * Transmission[s, r1, r, h] for r1 in REGION if valid_links[r1, r]) +
            - sum(Transmission[s, r, r1, h] for r1 in REGION if valid_links[r, r1]) >= load[s, r, h] * time_step - SheddedLoad[s, r, h]

        SheddedLoadCap[s in SCENARIO, r in REGION, h in PERIOD],
            SheddedLoad[s, r, h] <= load[s, r, h] * time_step * load_shedding_ratio

        SystemTotalEmissions[s in SCENARIO],
            TotalEmissions[s] == 8760 /(time_step * no_periods) * sum(Electricity[s, r, p, h]/eta[p]*emissionfactor[p] for r in REGION, p in TECH, h in PERIOD) # ton CO2

        # CARBON CAP
        CarbonCap[s in SCENARIO],
		    TotalEmissions[s] <= carbon_cap * sum(load[s, r, h] * time_step - SheddedLoad[s, r, h] for r in REGION, h in PERIOD)    # carbon_cap in ton/MWh
        
        SystemOperationalCost[s in SCENARIO],
            OperationalCost[s] == 8760 /(time_step * no_periods) * (sum(Electricity[s, r, p, h]*(fuel_cost[p]/eta[p] + var_cost[p]) for r in REGION, p in TECH, h in PERIOD))

        SystemFixedCost[s in SCENARIO],
            FixedCost[s] == sum(Capacity[r, p]*fixed_cost[p] for r in REGION, p in TECH)

        SystemInvestmentCost,
            InvestmentCost == sum(Capacity[r, p]*inv_cost[p]*crf[p] for r in REGION, p in TECH) +
                           + sum(TransmissionCapacity[r, r1]*distance[r, r1] for r in REGION, r1 in REGION if r1 > r && valid_links[r, r1])*transmissioncost*crf_t
            
        SystemSheddedLoad[s in SCENARIO],
            TotalSheddedLoadCost[s] == load_shedding_cost * 8760 /(time_step * no_periods) * sum(SheddedLoad[s, r, h] for r in REGION, h in PERIOD)

    end #constraints

    @objective m Min begin
        InvestmentCost + sum(prob[s]*(OperationalCost[s] + FixedCost[s] + TotalSheddedLoadCost[s]) for s in SCENARIO)
    end
    return (;m, Capacity, Electricity, TransmissionCapacity, TotalEmissions, OperationalCost, FixedCost, InvestmentCost, TotalSheddedLoadCost, PlannedOutage)
end 

