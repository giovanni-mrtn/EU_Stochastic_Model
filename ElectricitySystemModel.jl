"""
RunSimulationModel(title, SELECTEDYEARS, Capacity_r, TransmissionCapacity_r, problem, input, time_series_data)

Run deterministic simulations across `SELECTEDYEARS` using fixed capacities. Returns averages and a table for reporting.
Only used when `problem.simulate_results = true`.
"""
function RunSimulationModel(title, SELECTEDYEARS, Capacity_r, TransmissionCapacity_r, problem, input, time_series_data)
    @unpack load_shedding_cost, loss_of_load_penalty, time_step = problem
    @unpack simulated_load = time_series_data
    result = []

    for s in SELECTEDYEARS
        TotalLoad_r = sum(simulated_load[s,:,:]) * time_step
        simulation_data = prepare_simulation_data(problem, input, time_series_data, s)
                                                  
        model = Build_Simulation_Model(Capacity_r, TransmissionCapacity_r, problem, input, simulation_data)
        @unpack m, Electricity, TotalEmissions, OperationalCost, FixedCost, InvestmentCost, TotalSheddedLoadCost, TotalLoadLossCost = model
        println("\nSolving simulation model (simulation year $(s+1978))...")
        optimize!(m)

        # Collect simulation results
        ObjVal_r = objective_value(m) / 1e6
        TotalCosts_r = (value.(InvestmentCost) + value.(OperationalCost) + value.(FixedCost) + value.(TotalSheddedLoadCost) + value.(TotalLoadLossCost) ) /1e6
        TotalCostsWithoutLoadLoss_r = (value.(InvestmentCost) + value.(OperationalCost) + value.(FixedCost) + value.(TotalSheddedLoadCost)) / 1e6 
        InvestmentCost_r = value.(InvestmentCost) / 1e6
        OperationalCost_r = value.(OperationalCost) / 1e6
        FixedCost_r = value.(FixedCost) / 1e6
        TotalEmissions_r = value.(TotalEmissions) / 1e6
        TotalSheddedLoadCost_r = value.(TotalSheddedLoadCost) / 1e6
        TotalLoadLossCost_r = value.(TotalLoadLossCost) / 1e6
        SheddedLoad_r = value.(TotalSheddedLoadCost) / load_shedding_cost / 1e6 
        LoadLoss_r = value.(TotalLoadLossCost) / loss_of_load_penalty / 1e6 
        SatisfiedLoad_r = (TotalLoad_r - value.(TotalSheddedLoadCost) / load_shedding_cost - value.(TotalLoadLossCost) / loss_of_load_penalty ) / 1e6
        UnitProductionCost_r = TotalCostsWithoutLoadLoss_r / SatisfiedLoad_r
      
        # Append results to the result array
        push!(result, (ObjVal_r, TotalCosts_r, TotalCostsWithoutLoadLoss_r, InvestmentCost_r, FixedCost_r, OperationalCost_r, TotalEmissions_r, TotalSheddedLoadCost_r, TotalLoadLossCost_r, SatisfiedLoad_r, SheddedLoad_r, LoadLoss_r, UnitProductionCost_r)) 
        
        # Reset the model (optional, depending on your use case)
        m = nothing
    end
    
    # Convert the result array to a DataFrame
    df = DataFrame(result)
    
    # Convert the DataFrame to a NamedArray
    named_array = NamedArray(Matrix(df), (1:size(df, 1), names(df)))

    # Calculate the averages for each column
    averages = mean(named_array, dims=1)  # Compute mean along the first dimension (rows)
    averages = vec(averages)  # Flatten into a 1D vector for easier access

    # Create a named tuple for averages
    AverageObjVal = averages[1]
    AverageCosts = averages[2]
    AverageTotalCostsWithoutLoadLoss = averages[3]
    AverageInvestmentCost = averages[4]
    AverageFixedCost = averages[5]
    AverageOperationalCost = averages[6]
    AverageTotalEmissions = averages[7]
    AverageTotalSheddedLoadCost = averages[8]
    AverageTotalLoadLossCost = averages[9]
    AverageSatisfiedLoad = averages[10]
    AverageSheddedLoad = averages[11]
    AverageLoadLoss = averages[12]
    AverageUnitProductionCost = averages[13]
    
    # Add the averages row as the first row (so it becomes first column after transpose)
    extended_array = vcat(reshape(averages, 1, :), named_array)  # Prepend averages as first row
    
    # Update the row names to include "Average" as the first row
    new_row_names = vcat(["Average"], 1:size(df, 1))
    extended_named_array = NamedArray(extended_array, (new_row_names, names(df)))

    # Transpose to get final table layout (averages is now first column)
    transposed_array = extended_named_array'
    
    # Prepare column headers with "Average" first
    column_headers = vcat("Average", "Year " .* string.(SELECTEDYEARS .+(1979 - 1)))

    # Prepare the table for saving
    table = [(
        title, 
        transposed_array,
        column_headers,
        ["Objective value",
        "Total costs (M€)",
        "Total costs without load loss (M€)",
        "Investment cost (M€)",
        "Fixed cost (M€)",
        "Operational cost (M€)",
        "CO2 emissions (Mt)",
        "Load shedding cost (M€)",
        "Load loss cost (M€)",
        "Satisfied load (TWh)",
        "Shedded Load (TWh)",
        "Load loss (TWh)",
        "Unit production cost (€/MWh)"]
    )]
    
    # Return the named tuple of averages and the table
    return (; AverageObjVal, 
    AverageCosts, 
    AverageTotalCostsWithoutLoadLoss, 
    AverageInvestmentCost, 
    AverageFixedCost, 
    AverageOperationalCost, 
    AverageTotalEmissions, 
    AverageTotalSheddedLoadCost, 
    AverageTotalLoadLossCost, 
    AverageSatisfiedLoad, 
    AverageSheddedLoad, 
    AverageLoadLoss, 
    AverageUnitProductionCost, 
    table)
end

